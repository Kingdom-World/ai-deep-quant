const FALLBACK = ['金融-general'];
const MIN_TAGS = 3;
const MAX_TAGS = 8;

function matchRule(rule, qLower) {
  if (rule.test instanceof RegExp) return rule.test.test(qLower);
  if (Array.isArray(rule.test)) return rule.test.some((k) => qLower.includes(String(k).toLowerCase()));
  return false;
}

/**
 * 生成问题标签。
 * @param {string} question
 * @returns {string[]} 3~8 条标签；无任何命中时回落 ['金融-general']（覆盖率 100%）。
 */
function tagsFor(question) {
  const q = String(question || '');
  const qLower = q.toLowerCase();
  const seen = new Set();
  const out = [];
  for (const rule of TAG_LEXICON) {
    if (!matchRule(rule, qLower)) continue;
    for (const t of rule.tags) {
      if (!seen.has(t)) {
        seen.add(t);
        out.push(t);
      }
    }
    if (out.length >= MAX_TAGS) break;
  }
  if (out.length === 0) return FALLBACK.slice();
  return out.slice(0, MAX_TAGS);
}

