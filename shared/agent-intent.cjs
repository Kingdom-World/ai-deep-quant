// ─────────────────────────────────────────────────────────────
// Agent 越界意图闸门（#71）
//
//   存在的理由（实测缺陷，不是假想风险）：
//     「推荐一只明天涨停的股票」→ brain.lookup() 命中 term-limit-up-down（涨跌停术语）
//     「哪只股票一定涨」          → 命中 method-adjust-illusion（复权幻觉）
//   根因：2-gram 相似度**只看词面重叠、不看意图**。「涨停」「一定涨」这些词
//   在知识库里当然存在，于是超范围问题被当成术语问题回答了。
//
//   🔴 为什么这比"胡说"更危险：它**不是编造**，而是**答非所问却带着真出处**。
//   用户看到的是一条正经的涨跌停规则解释，还标着「🧠 来自学习知识库 · 匹配置信 62%」
//   ⇒ 看起来像答案。这比明说"不知道"更伤信任，也更难被发现。
//
//   ── 三条设计裁定 ──
//
//   ① 🔴 **闸门只拦"越界"，绝不拦"正常问题"**。
//      越界的定义：只有当问题**要求我做我做不到的事**（荐股/收益承诺/预测未来/
//      医疗法律建议）才算越界。「夏普比率是什么」不是越界——它在知识库里有答案，
//      必须照常回答。闸门过宽会把产品变成"什么都不答"，那是另一种失败。
//
//   ② 🔴 **不依赖 prompt，靠代码前置判断**。
//      理由同 MEMORY.md 的既有纪律：prompt 拦不住的事要靠架构拦。
//      本模块是纯函数、零 IO，在任何 LLM 调用之前执行 —— 被拦的问题
//      **连云端模型都不发起请求**（省额度 + 杜绝模型自己"圆场"）。
//
//   ③ ⚠️ **宁可漏拦，不可误拦**。
//      判据用「强特征词」而非「主题词」：必须出现**祈使/断言型表述**
//      （推荐/给我/预测/保证/一定），而不是仅仅出现"股票""涨跌"这类中性名词。
//      每条规则都写明命中的**具体词**，便于事后审查为什么某句被拦。
// ─────────────────────────────────────────────────────────────

/**
 * 越界意图类别。label 用于回答里的显式声明（不藏着，让用户知道为什么没答）。
 */
const OUT_OF_SCOPE = {
  stock_pick: { label: '个股荐股', refuse: '我不能推荐具体个股或给出买卖时机判断——这属于投资建议，超出本平台的演示范围。' },
  return_promise: { label: '收益承诺', refuse: '我不能承诺任何收益。平台所有内容都是学术研究演示，历史数据不预示未来表现。' },
  future_predict: { label: '未来预测', refuse: '我不能预测未来价格或指数点位。未来走势受多重因素影响，不存在可靠的方法可以提前确定。' },
  domain_advice: { label: '专业建议', refuse: '我只能回答量化研究相关的问题。医疗、法律、投资等专业判断请咨询有资质的专业人士。' },
  capability_promise: { label: '能力承诺', refuse: '我不能保证平台能带来收益。本平台是学术研究演示，所有数字都可核查，但不构成任何投资建议。' },
};

/**
 * 越界特征表。
 * 🔴 每条都写明**为什么这么写**——这类规则最容易被后人"优化"掉，
 *   而没人记得当初为什么必须这么判。
 *
 * ⚠️ 全部使用**强特征**（祈使/断言动词）。刻意**不含**：
 *   「股票」「基金」「买」「卖」「涨跌」「赚」「行情」等中性名词 ——
 *   它们出现在正常研究问题里（"回测里怎么处理涨跌停"），
 *   把它们当越界特征会把产品变成"什么都不答"。
 */
const RULES = [
  {
    kind: 'stock_pick',
    // 「推荐」「荐股」「挑一只」「选哪只」= 明确要别人替他做决策
    //⚠️ 「推荐」后必须跟**具体标的类别**（股票/个股/基金/标的/币）——
    //   否则「推荐一下量化学习路径」「推荐一本书」这类正常请求会被误拦（实测踩过）。
    patterns: [
      /推荐.{0,6}(股票|个股|基金|标的|个股池)/,
      /(荐股|荐股池)/,
      /挑一?只/,
      /选哪只/,
      /哪只.{0,4}(涨|好|值得)/,
      /(买|卖|持有).{0,4}(哪只|什么)/,
      // 「推荐一只…」「推荐哪只…」—— 量化了"一只/哪只"就是明确要标的
      /推荐(一?只|哪只|什么|几个|几只)/,
      /选(一?只|哪只|什么|几个|几只)/,
      // 买入/卖出时机问句：「现在是买入 X 的好时机吗」「该买还是该卖」
      /是(不是|是否)?.{0,8}(买入|卖出|买进|卖出|加仓|减仓).{0,6}(好时机|合适|宜)/,
      /(买入|卖出|买进|卖出).{0,8}(好时机|合适吗|宜吗)/,
      /该(买|卖|加仓|减仓)还是(卖|买|观望)/,
    ],
  },
  {
    kind: 'return_promise',
    // 断言型承诺：「保证」「一定能」+ 收益词。裸「赚」不算（"回测收益率怎么算"是正常问题）
    // 🔴 负向排除（实测踩过）：「零风险利率」「无风险利率」是**标准金融术语**
    //   （CAPM 里的 rf），是正常研究问题，不是收益承诺。
    //   判据：这些词后面若跟「利率/溢价/系数/资产」⇒ 术语，放行。
    patterns: [
      /保[证障]?.{0,6}(赚|收益|盈利|回报)/,
      /稳赚/,
      /包赚/,
      /一定(能)?(赚|涨|盈利)/,
      /肯定(能)?(赚|涨)/,
      /无风险.{0,4}(收益|赚)/,
      // 「零风险/无风险」只有**不接术语后缀**时才算承诺
      /(零风险|无风险)(?!.{0,4}(利率|溢价|系数|资产|利率rf|的))/,
    ],
  },
  {
    kind: 'future_predict',
    // 要未来点位/涨跌/结果。注意「明天」本身不够（"明天开盘几点"不是越界）
    patterns: [
      /预测.{0,8}(明天|后天|下周|点位|指数|涨跌|行情|股价|价格)/,
      /(明天|后天|下周|未来).{0,6}(涨还是跌|会涨|会跌|点位是多少|怎么走|如何走)/,
      /(会|能不能|会不会)(涨|跌).{0,4}吗?$/,
      /(明天|后天|下周).{0,6}(会)?(涨|跌)/,
      /(涨还是跌|涨还是跌|是涨是跌)/,
    ],
  },
  {
    kind: 'domain_advice',
    // 医疗/法律/税务等专业建议。量化类术语（因子/回测/策略）刻意不在此列
    patterns: [/(该|要|我)?吃.{0,4}(什么)?药/, /(诊断|症状).{0,6}(是|什么|怎么办)/, /(犯法|判几年|拘留|诉讼)/, /(报税|抵扣).{0,6}(怎么|多少)/],
  },
  {
    kind: 'capability_promise',
    // 对**本平台能力**的承诺（区别于 return_promise 的市场收益）
    patterns: [/(这个|本站|本)平台.{0,8}(能|可以)?(保证|确保)/, /(能|可以)?(保证|确保).{0,8}(赚钱|盈利|收益)/],
  },
];

/** 归一化：去空白、全角转半角（用户输入里全角空格很常见） */
function norm(s) {
  return String(s || '')
    .replace(/　/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * 判定是否越界。
 * @param {string} q 用户问题
 * @returns {{outOfScope:boolean, kind?:string, label?:string, refuse?:string, matched?:string}|{outOfScope:false}}
 */
function detect(q) {
  const s = norm(q);
  if (!s) return { outOfScope: false };
  for (const rule of RULES) {
    for (const re of rule.patterns) {
      const m = s.match(re);
      if (m) {
        const meta = OUT_OF_SCOPE[rule.kind];
        return {
          outOfScope: true,
          kind: rule.kind,
          label: meta.label,
          refuse: meta.refuse,
          matched: m[0], // 回显命中片段：便于日志排查「为什么这句被拦」
        };
      }
    }
  }
  return { outOfScope: false };
}

/** 越界时的完整回答（显式说明 + 给出平台**能**做什么，不空手拒绝） */
function refusal(q, d) {
  const lines = [
    `⚠️ ${d.label}类问题我不回答：${d.refuse}`,
    '',
    '我可以帮你做的是：',
    '· 「分析 AAPL」—— 个股五因子解读（基于真实历史行情）',
    '· 「今天观察什么」—— 股票池因子评分排名',
    '· 「市场情绪怎么样」—— 温度计与涨跌结构',
    '· 「什么是夏普比率」—— 量化名词解释（带出处）',
    '· 「回测怎么用」—— 策略回测指引',
  ];
  return lines.join('\n');
}

module.exports = { detect, refusal, OUT_OF_SCOPE, RULES, norm };